class TestPQHyperbolic:
    def test_goldens_x64(self):
        with enable_x64():
            p, q = _pq_hyperbolic(jnp.asarray(PQ_X))
            np.testing.assert_allclose(np.asarray(p), P_GOLD, rtol=1e-6)
            np.testing.assert_allclose(np.asarray(q), Q_GOLD, rtol=1e-6)

    def test_asymptotic_seam_continuity(self):
        with enable_x64():
            below = _pq_hyperbolic(jnp.array([30.0 - 1e-9]))
            above = _pq_hyperbolic(jnp.array([30.0 + 1e-9]))
            for b, a in zip(below, above):
                np.testing.assert_allclose(np.asarray(b), np.asarray(a),
                                           rtol=1e-6)

    def test_float32_reasonable(self):
        p, q = _pq_hyperbolic(jnp.asarray(PQ_X, dtype=jnp.float32))
        np.testing.assert_allclose(np.asarray(p), P_GOLD, rtol=5e-4)
        np.testing.assert_allclose(np.asarray(q), Q_GOLD, rtol=5e-4)

    def test_grad_finite(self):
        g = jax.vmap(jax.grad(lambda x: _pq_hyperbolic(x)[0]))(jnp.asarray(PQ_X))
        assert bool(jnp.all(jnp.isfinite(g)))


class TestTNFW:
    @pytest.mark.parametrize("c,sig_gold,bsig_gold", [
        (3.0, TJ_SIGMA_C3, TJ_BSIGMA_C3),
        (6.0, TJ_SIGMA_C6, TJ_BSIGMA_C6),
        (15.0, TJ_SIGMA_C15, TJ_BSIGMA_C15),
    ])
    def test_kernel_goldens(self, c, sig_gold, bsig_gold):
        with enable_x64():
            f = np.asarray(_tj_sigma_dl(jnp.asarray(GOLD_X), c))
            g = np.asarray(_tj_bsigma_dl(jnp.asarray(GOLD_X), c))
        rtol = np.where(_TJ_WINDOW, 5e-4, 1e-8)
        assert np.all(np.abs(f - sig_gold) <= rtol * np.abs(sig_gold) + 1e-12)
        assert np.all(np.abs(g - bsig_gold) <= rtol * np.abs(bsig_gold))

    def test_sigma_zero_beyond_truncation(self):
        s = tnfw_sigma(jnp.array([6.0, 7.0, 50.0]), 1e15, 1.0, 6.0)
        np.testing.assert_array_equal(np.asarray(s), 0.0)

    def test_2d_mass_conservation(self):
        # π R² Σ̄ → M_trunc = 4π ρ_s r_s³ m_nfw(c) for R ≥ c r_s
        rho_s, r_s, c = 1.4e15, 0.2, 6.0
        R = jnp.array([1.2001, 5.0, 80.0])
        m2d = np.pi * np.asarray(R)**2 * np.asarray(
            tnfw_mean_sigma(R, rho_s, r_s, c))
        m_t = 4.0 * np.pi * rho_s * r_s**3 * float(_m_nfw(jnp.asarray(c)))
        np.testing.assert_allclose(m2d, m_t, rtol=1e-5)
        np.testing.assert_allclose(
            float(tnfw_mass(jnp.array([100.0]), rho_s, r_s, c)[0]),
            m_t, rtol=1e-6)

    def test_delta_sigma_identity(self):
        R = jnp.logspace(-2, 1, 40)
        ds = tnfw_delta_sigma(R, 1.4e15, 0.2, 6.0)
        expect = (tnfw_mean_sigma(R, 1.4e15, 0.2, 6.0)
                  - tnfw_sigma(R, 1.4e15, 0.2, 6.0))
        np.testing.assert_allclose(np.asarray(ds), np.asarray(expect),
                                   rtol=1e-6)

    def test_nfw_limit_inside_truncation(self):
        # deep inside a very extended truncation the projection is NFW-like
        R = jnp.logspace(-2, -0.5, 10)
        s_t = np.asarray(tnfw_sigma(R, 1.4e15, 0.2, 100.0))
        s_n = np.asarray(nfw_sigma(R, 1.4e15, 0.2))
        np.testing.assert_allclose(s_t, s_n, rtol=1e-2)

    def test_abel_projection(self):
        # analytic Σ vs numerical LOS integration of the truncated density
        from scipy.integrate import quad
        with enable_x64():
            rho_s, r_s, c = 1.4e15, 0.2, 6.0
            for R in (0.05, 0.3, 1.0):
                zmax = np.sqrt((c * r_s)**2 - R**2)
                num = 2.0 * quad(
                    lambda zz: float(tnfw_rho(
                        jnp.array([np.sqrt(R**2 + zz**2)]), rho_s, r_s, c)[0]),
                    0.0, zmax, limit=200)[0]
                ana = float(tnfw_sigma(jnp.array([R]), rho_s, r_s, c)[0])
                np.testing.assert_allclose(ana, num, rtol=3e-3)

    def test_uk_alias(self):
        assert tnfw_uk is nfw_uk_jax

    def test_grads_finite_at_branch_points(self):
        c = 6.0
        xs = jnp.array([0.5, 0.99, 0.9999, 1.0, 1.0001, 1.01, 2.0,
                        5.999, 6.0, 6.001, 10.0])
        for fn in (tnfw_sigma, tnfw_mean_sigma):
            g = jax.vmap(jax.grad(
                lambda x: fn(jnp.array([x]), 1e6, 1.0, c)[0]))(xs)
            assert bool(jnp.all(jnp.isfinite(g))), fn.__name__
        gc = jax.vmap(lambda x: jax.grad(
            lambda cc: tnfw_sigma(jnp.array([x]), 1e6, 1.0, cc)[0])(c))(xs)
        assert bool(jnp.all(jnp.isfinite(gc)))


class TestBMO:
    def test_kernel_goldens(self):
        with enable_x64():
            f = np.asarray(_bmo_sigma_dl(jnp.asarray(GOLD_X), 12.5))
            g = np.asarray(_bmo_bsigma_dl(jnp.asarray(GOLD_X), 12.5))
            m = np.asarray(_m_bmo_dl(jnp.asarray(GOLD_X), 12.5))
        np.testing.assert_allclose(f, BMO_SIGMA_T12P5, rtol=1e-7)
        np.testing.assert_allclose(g, BMO_BSIGMA_T12P5, rtol=1e-7)
        np.testing.assert_allclose(m, BMO_MASS_T12P5, rtol=1e-7)

    @pytest.mark.parametrize("tau", [3.0, 12.5, 25.0])
    def test_mass_total_golden(self, tau):
        with enable_x64():
            np.testing.assert_allclose(float(_m_bmo_tot_dl(jnp.asarray(tau))),
                                       BMO_MTOT[tau], rtol=1e-10)

    def test_nfw_limit_large_tau(self):
        with enable_x64():
            R = jnp.logspace(-2, 0.5, 20)
            s_b = np.asarray(bmo_sigma(R, 1.4e15, 0.2, 1e4))
            s_n = np.asarray(nfw_sigma(R, 1.4e15, 0.2))
            np.testing.assert_allclose(s_b, s_n, rtol=1e-3)
            d_b = np.asarray(bmo_delta_sigma(R, 1.4e15, 0.2, 1e4))
            d_n = np.asarray(nfw_delta_sigma(R, 1.4e15, 0.2))
            np.testing.assert_allclose(d_b, d_n, rtol=2e-3)

    def test_abel_projection(self):
        from scipy.integrate import quad
        with enable_x64():
            rho_s, r_s, tau = 1.4e15, 0.2, 12.5
            for R in (0.05, 0.5, 3.0):
                num = 2.0 * quad(
                    lambda zz: float(bmo_rho(
                        jnp.array([np.sqrt(R**2 + zz**2)]), rho_s, r_s, tau)[0]),
                    0.0, np.inf, limit=400)[0]
                ana = float(bmo_sigma(jnp.array([R]), rho_s, r_s, tau)[0])
                np.testing.assert_allclose(ana, num, rtol=3e-3)

    def test_mass_conservation_2d(self):
        with enable_x64():
            rho_s, r_s, tau = 1.4e15, 0.2, 12.5
            R_big = 3000.0
            m2d = (np.pi * R_big**2
                   * float(bmo_mean_sigma(jnp.array([R_big]), rho_s, r_s, tau)[0]))
            m_tot = float(bmo_mass_total(rho_s, r_s, tau))
            # Σ̄ converges to M_tot/(πR²) only logarithmically slowly (ρ ∝ r⁻⁷)
            np.testing.assert_allclose(m2d, m_tot, rtol=5e-3)
            m3d = float(bmo_mass(jnp.array([1e5 * r_s]), rho_s, r_s, tau)[0])
            np.testing.assert_allclose(m3d, m_tot, rtol=1e-6)

    def test_uk_goldens(self):
        with enable_x64():
            uk = np.asarray(bmo_uk_jax(jnp.asarray(BMO_UK_K / 0.2),
                                       jnp.array([0.2]), jnp.array([15.0])))[:, 0]
        np.testing.assert_allclose(uk, BMO_UK_T15P0, rtol=5e-5)

    def test_uk_low_k_guard(self):
        uk = bmo_uk_jax(jnp.array([1e-7]), jnp.array([0.2]), jnp.array([15.0]))
        np.testing.assert_allclose(float(uk[0, 0]), 1.0)

    def test_grads_finite(self):
        xs = jnp.array([0.005, 0.5, 0.99, 1.0, 1.01, 2.0, 12.5, 40.0])
        for fn in (bmo_sigma, bmo_mean_sigma):
            g = jax.vmap(jax.grad(
                lambda x: fn(jnp.array([x]), 1e6, 1.0, 12.5)[0]))(xs)
            assert bool(jnp.all(jnp.isfinite(g))), fn.__name__
        gt = jax.grad(lambda t: bmo_uk_jax(jnp.array([1.0, 1e-6]),
                                           jnp.array([0.2]),
                                           jnp.array([t])).sum())(15.0)
        assert bool(jnp.isfinite(gt))


class TestHernquist:
    def test_kernel_goldens(self):
        with enable_x64():
            f = np.asarray(_hern_sigma_dl(jnp.asarray(GOLD_X)))
            g = np.asarray(_hern_bsigma_dl(jnp.asarray(GOLD_X)))
        np.testing.assert_allclose(f, HERN_SIGMA, rtol=1e-7)
        np.testing.assert_allclose(g, HERN_BSIGMA, rtol=1e-7)

    def test_enclosed_mass_identity(self):
        m_tot, r_b = 3e11, 0.005
        r = jnp.array([0.001, 0.005, 0.05, 5.0])
        m = np.asarray(hernquist_mass(r, m_tot, r_b))
        x = np.asarray(r) / r_b
        np.testing.assert_allclose(m, m_tot * x**2 / (1 + x)**2, rtol=1e-6)

    def test_2d_mass_convergence(self):
        with enable_x64():
            m_tot, r_b = 3e11, 0.005
            R = 5.0  # x = 1000
            m2d = np.pi * R**2 * float(
                hernquist_mean_sigma(jnp.array([R]), m_tot, r_b)[0])
            np.testing.assert_allclose(m2d, m_tot, rtol=3e-3)

    def test_abel_projection(self):
        from scipy.integrate import quad
        with enable_x64():
            m_tot, r_b = 3e11, 0.005
            for R in (0.002, 0.005, 0.05):
                num = 2.0 * quad(
                    lambda zz: float(hernquist_rho(
                        jnp.array([np.sqrt(R**2 + zz**2)]), m_tot, r_b)[0]),
                    0.0, np.inf, limit=400)[0]
                ana = float(hernquist_sigma(jnp.array([R]), m_tot, r_b)[0])
                np.testing.assert_allclose(ana, num, rtol=3e-3)

    def test_delta_sigma_identity(self):
        R = jnp.logspace(-3, 0, 30)
        ds = hernquist_delta_sigma(R, 3e11, 0.005)
        expect = (hernquist_mean_sigma(R, 3e11, 0.005)
                  - hernquist_sigma(R, 3e11, 0.005))
        np.testing.assert_allclose(np.asarray(ds), np.asarray(expect),
                                   rtol=1e-5)

    def test_grads_finite(self):
        xs = jnp.array([0.01, 0.5, 0.99, 1.0, 1.01, 2.0, 100.0])
        for fn in (hernquist_sigma, hernquist_mean_sigma):
            g = jax.vmap(jax.grad(
                lambda x: fn(jnp.array([x]), 1e12, 1.0)[0]))(xs)
