class TestNfwParamsFromMass:
    def test_matches_haloprofile(self, planck_cosmo):
        # regression on the mdef_delta_rho extraction: bit-compatible with
        # HaloProfile.rho_s_and_rs for the JAX-native dutton14/200c path
        hp = HaloProfile({}, cm_relation="dutton14", mdef="200c")
        m = jnp.array([1e13, 1e14, 1e15])
        z = 0.4
        rho_hp, rs_hp = hp.rho_s_and_rs(m, z, planck_cosmo)
        c = hp.concentration(m, z)
        rho_f, rs_f, r_delta = nfw_params_from_mass(m, c, z, planck_cosmo,
                                                    "200c")
        np.testing.assert_allclose(np.asarray(rho_f), np.asarray(rho_hp),
                                   rtol=1e-7)
        np.testing.assert_allclose(np.asarray(rs_f), np.asarray(rs_hp),
                                   rtol=1e-7)
        np.testing.assert_allclose(np.asarray(r_delta),
                                   np.asarray(rs_f) * np.asarray(c), rtol=1e-6)

    @pytest.mark.parametrize("mdef", ["200m", "200c", "vir"])
    def test_mass_definition_closure(self, mdef, planck_cosmo):
        # sphere consistency: M = (4/3)π delta rho_ref r_delta³
        delta, rho_ref = mdef_delta_rho(mdef, 0.4, planck_cosmo)
        m = jnp.array([3e14])
        _, _, r_delta = nfw_params_from_mass(m, jnp.array([5.0]), 0.4,
                                             planck_cosmo, mdef)
        m_sphere = (4.0 / 3.0) * np.pi * delta * rho_ref * float(r_delta[0])**3
        np.testing.assert_allclose(m_sphere, 3e14, rtol=1e-5)
