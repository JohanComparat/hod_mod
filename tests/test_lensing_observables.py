"""Tests for hod_mod.observables.lensing (Σ_crit, mis-centering, 2-halo,
strong lensing, ClusterLensingPrediction).

Σ_crit goldens generated by make_lensing_goldens.py against the reference
halo_lensing implementation on colossus planck18 (h=0.6766, Ωm=0.3111).
"""

