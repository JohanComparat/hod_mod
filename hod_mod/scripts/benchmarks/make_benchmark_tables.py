#!/usr/bin/env python
"""Generate the More+2015 benchmark tables for the docs, from the result JSONs.

``benchmark_more2015.rst`` and ``hod_more2015.rst`` both present the same four
fits.  Kept by hand they drifted apart: before this script they disagreed on the
primary χ²/dof (1.974 vs 1.967), on the free-cosmology χ² (56.53/33 vs 35.70/33)
and on the recovered :math:`S_8` (0.813 vs 0.778) — three different answers to
questions with one answer each.  Generating the tables from
``benchmark_result.json`` removes the drift by construction.

Same pattern as :func:`hod_mod.scripts.fitting.bgs_ls10.plot_wp_survey._write_permodel_rst`,
which already generates ``docs/_permodel_auto.rst``: emit a fragment, and let the
pages ``.. include::`` it.

Usage::

    python -m hod_mod.scripts.benchmarks.make_benchmark_tables
    HOD_MOD_RESULTS=~/data/hod_mod_results python -m hod_mod.scripts.benchmarks.make_benchmark_tables

Writes ``docs/_benchmark_more2015_auto.rst``.
"""

from __future__ import annotations

import argparse
import datetime
import json
import os

import numpy as np

from hod_mod.paths import results_root

# The four variants, in the order both pages present them.
VARIANTS = [
    ("more2015_logM11_12",          r"``logM11_12`` — :math:`\log M_*>11.1`"),
    ("more2015_logM11p3_12",        r"``logM11p3_12`` — :math:`\log M_*>11.3`"),
    ("more2015_logM11p4_12",        r"``logM11p4_12`` — :math:`\log M_*>11.4`"),
    ("more2015_logM11_12_freecosmo", r"``logM11_12_freecosmo`` — free :math:`\Omega_m, S_8`"),
]

# Display order + RST label for the fitted parameters.
PARAM_LABEL = {
    "Omega_m":    r":math:`\Omega_m`",
    "S8":         r":math:`S_8`",
    "h":          r":math:`h`",
    "log10mmin":  r"``log10mmin``",
    "sigma_logm": r"``sigma_logm``",
    "log10m1":    r"``log10m1``",
    "alpha":      r"``alpha``",
    "kappa":      r"``kappa``",
}


def _load(model: str, root: str) -> dict | None:
    path = os.path.join(root, "benchmarks", model, "benchmark_result.json")
    if not os.path.exists(path):
        return None
    with open(path) as fh:
        d = json.load(fh)
    d["_path"] = path
    d["_mtime"] = datetime.date.fromtimestamp(os.path.getmtime(path)).isoformat()
    # The posterior, when the MCMC finished.  Medians are quoted alongside the
    # MAP because for these fits the two genuinely differ (kappa in particular).
    fc = os.path.join(root, "benchmarks", model, "flatchain.npz")
    if os.path.exists(fc):
        npz = np.load(fc, allow_pickle=True)
        chain = np.asarray(npz["flatchain"], float)
        names = [str(n) for n in npz["param_names"]]
        p16, p50, p84 = np.percentile(chain, [16, 50, 84], axis=0)
        d["_post"] = {n: (p50[i], p50[i] - p16[i], p84[i] - p50[i])
                      for i, n in enumerate(names)}
        d["_nsamples"] = chain.shape[0]
    return d


def _status_rst(d: dict) -> str:
    # run_benchmark's own criterion is chi2_ndof < 2.0; echo its verdict rather
    # than re-deriving it, so the page can never disagree with the JSON.
    return "**PASSED**" if d.get("status") == "pass" else "**FAILED**"


def build(root: str) -> list[str]:
    L: list[str] = [
        ".. GENERATED by hod_mod.scripts.benchmarks.make_benchmark_tables — do not edit.",
        ".. Source: $HOD_MOD_RESULTS/benchmarks/more2015_*/benchmark_result.json",
        "",
    ]

    # ---- summary table ----------------------------------------------------
    L += [
        ".. list-table:: More+2015 benchmark summary",
        "   :header-rows: 1",
        "   :widths: 34 10 8 12 12 14",
        "",
        "   * - Variant",
        "     - :math:`\\chi^2`",
        "     - dof",
        "     - :math:`\\chi^2`/dof",
        "     - published",
        "     - Status",
    ]
    for model, label in VARIANTS:
        d = _load(model, root)
        if d is None:
            L += [f"   * - {label}", "     - —", "     - —", "     - —", "     - —",
                  "     - *no result on disk*"]
            continue
        pub = d.get("published_chi2_ndof")
        L += [
            f"   * - {label}",
            f"     - {d['chi2']:.2f}",
            f"     - {d['ndof']}",
            f"     - **{d['chi2_ndof']:.3f}**",
            f"     - {pub:.1f}" if pub is not None else "     - —",
            f"     - {_status_rst(d)}",
        ]
    L.append("")

    # ---- per-variant parameter tables -------------------------------------
    for model, label in VARIANTS:
        d = _load(model, root)
        if d is None:
            continue
        # rubric, not a section heading: this fragment is included by two pages
        # at different nesting depths, and a fixed underline character would put
        # the variants at the wrong level in one of them.  hod_more2015.rst
        # already uses `.. rubric::` for exactly these sub-blocks.
        L += [f".. rubric:: {label} — best fit", ""]
        post = d.get("_post")
        L += [
            f".. list-table:: MAP{' and posterior median' if post else ''} vs published",
            "   :header-rows: 1",
            "   :widths: 16 14 " + ("18 " if post else "") + "18 12",
            "",
            "   * - Parameter",
            "     - MAP",
        ]
        if post:
            L.append("     - median :math:`\\pm68\\%`")
        L += ["     - Published", "     - Deviation"]

        pub = d.get("published_params", {})
        dev = d.get("param_deviations_sigma", {})
        for name, plabel in PARAM_LABEL.items():
            if name not in d["params"]:
                continue
            L += [f"   * - {plabel}", f"     - {d['params'][name]:.3f}"]
            if post:
                if name in post:
                    m, lo, hi = post[name]
                    L.append(f"     - {m:.3f} :math:`^{{+{hi:.3f}}}_{{-{lo:.3f}}}`")
                else:
                    L.append("     - —")
            if name in pub:
                mu, sig = pub[name]
                L.append(f"     - {mu:.3f} ± {sig:.3f}")
            else:
                L.append("     - —")
            s = dev.get(name)
            if s is None or not np.isfinite(s):
                L.append("     - —")
            else:
                flag = " ⚠" if abs(s) >= 2.0 else ""
                L.append(f"     - {s:+.2f}σ{flag}")
        L.append("")

        note = [f"MAP :math:`\\chi^2/\\mathrm{{dof}} = {d['chi2']:.2f}/{d['ndof']} = "
                f"{d['chi2_ndof']:.3f}`.  Status: {_status_rst(d)}."]
        if post:
            note.append(f"Posterior from {d['_nsamples']:,} samples.")
        note.append(f"Result file dated {d['_mtime']}.")
        L += [" ".join(note), ""]

    return L


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results-root", default=None,
                    help="Results tree (default: hod_mod.paths.results_root())")
    ap.add_argument("--out", default=None,
                    help="Output .rst (default: docs/_benchmark_more2015_auto.rst)")
    args = ap.parse_args()

    root = args.results_root or os.fspath(results_root())
    out = args.out or os.path.join(
        os.path.dirname(os.path.dirname(os.path.dirname(
            os.path.dirname(os.path.abspath(__file__))))),
        "docs", "_benchmark_more2015_auto.rst")

    lines = build(root)
    with open(out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"Wrote {out}  ({len(lines)} lines, from {root}/benchmarks/more2015_*)")


if __name__ == "__main__":
    main()
